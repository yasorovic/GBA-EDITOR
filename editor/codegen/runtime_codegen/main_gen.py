# ─── point d'entrée ───────────────────────────────────────────────────────────

def generate_main(
    p: Project,
    all_scene_data: list[dict],   # list of {scene, bg_pairs, scene_actors, prefab_sprites}
    sound_assets: dict | None,
    prefab_actor_sprites: list,
    prefabs,
    emit,
    actor_defined_events: dict[str, set[str]] | None = None,
) -> bool:
    """Génère main.c multi-scène et le copie dans p.src_dir/."""
    prefab_actor_sprites = prefab_actor_sprites or []
    has_sound   = bool(sound_assets and (sound_assets.get("sfx") or sound_assets.get("music")))
    soundbank_h = p.build_dir / "soundbank.h"
    has_soundbank = has_sound and soundbank_h.exists()
    all_scenes  = [d["scene"] for d in all_scene_data]
    scene_names = [s.name for s in all_scenes]
    start_scene = (getattr(p.settings, "start_scene", None) or
                   (scene_names[0] if scene_names else ""))
    start_idx   = next((i for i, n in enumerate(scene_names) if n == start_scene), 0)

    # Copier gba_engine.h
    _src = RUNTIME_DIR / "include" / "gba_engine.h"
    if _src.exists():
        build_output.copy(_src, p.src_dir / "gba_engine.h")

    # ── Calcul des offsets globaux des actors ─────────────────────
    # Chaque scène repart de la base OAM 0 : une seule est
    # vivante à la fois, le scene_init efface `g_actors` et repose ses acteurs
    # depuis 0. Les offsets sont donc tous nuls, et `g_actors` est dimensionné
    # sur la scène la plus gourmande (max, pas somme).
    n_actors = project_actor_count(p)
    # La taille d'un bloc d'état de script : le plus gros état des modèles compilés (lua_compiler les a notés
    # scène par scène). Un en-tête, parce que chaque script doit le connaître pour y ranger sa structure.
    build_output.write(p.src_dir / "obj_state.h", "\n".join([
        "/* obj_state.h — generated by Backstage (do not edit) */",
        "#ifndef OBJ_STATE_H",
        "#define OBJ_STATE_H",
        "/* Bytes of the script state block each actor slot carries (the biggest model state, word aligned). */",
        f"#define OBJ_STATE_STRIDE {read_state_stride(p)}",
        "#endif",
        ""]))
    _state_cost = state_cost_line(p, n_actors)
    if _state_cost:
        emit("log_line", _state_cost)
    n_oam_entries = project_oam_entry_count(p)
    scene_offsets = [0] * len(all_scene_data)
    # `pi` par scène : plages de pool per-scène (symboles `<Scène>_<Prefab>`),
    # lues de `scene_oam_layout`. Chaque scène ne porte que les pools qu'elle
    # déclare, à leur place dans SA fenêtre.
    scene_pis = [scene_pi(p, d["scene"]) for d in all_scene_data]

    # ── Sprites : union de toutes les scènes ──────────────────────
    all_sprite_pairs: list = []
    for d in all_scene_data:
        all_sprite_pairs += d["scene_actors"] + d["extra_sprites"]
    all_sprite_pairs += prefab_actor_sprites
    # Un sprite qui ne sert QU'à une image d'interface n'est porté par aucun
    # acteur : sans ceci, ses tuiles ne partiraient jamais en VRAM.
    all_sprite_pairs += ui_image_sprites(p)

    sprite_offsets, sprite_nframes = sprite_offsets_for(p, all_sprite_pairs)

    # Bande de texte OBJ. La base de SLOTS OAM est PAR SCÈNE — juste après les
    # acteurs, avant les pools (ordre acteurs → UI → pools). La base de TUILES,
    # elle, reste l'union projet : les tuiles des sprites sont résidentes et
    # partagées, donc la 1re tuile OBJ libre est la queue de TOUS les sprites.
    _obj_alloc = obj_text_alloc(p)
    obj_text_tile = obj_tiles_used(p, all_sprite_pairs)
    _any_obj_ui = any(scene_obj_ui_slots(p, d["scene"]) > 0 for d in all_scene_data)

    # Débordement : BLOQUANT, et calculé même sans `emit`.
    if not check_main(p, all_scene_data, _obj_alloc, obj_text_tile, _any_obj_ui, emit):
        return False

    # Une seule fois par scène : `scene_init` et `scene_tick` relisent ce placement
    # (posé sur la scène par `apply_vram_layout`), ils ne le recalculent pas.
    scene_bgi: list[list[dict]] = []
    for d in all_scene_data:
        bgi_d = bg_info(p, d["scene"])
        apply_vram_layout(p, d["scene"], bgi_d, scene_text_reservation(p, d["scene"]))
        log_vram_layout(d["scene"], emit)
        scene_bgi.append(bgi_d)

    L: list[str] = include_lines(p, all_scene_data, scene_bgi, prefab_actor_sprites, has_sound, soundbank_h)
    L += extern_lines(p, all_scene_data, scene_pis, actor_defined_events)
    L += camera_table_lines(p)

    # ── Polices + table des textes ───────────────────────────────
    L += fonts_and_texts_lines(p, emit)

    # ── Tables d'animation par SpriteAsset (dédupliquées) ────────
    # Les sprites des IMAGES d'interface en font partie : `g_ui_images` pointe
    # ces tables-là, donc elles doivent exister — et être émises AVANT.
    _all_sprites_flat = [
        pair
        for d in all_scene_data
        for pair in d["scene_actors"]
    ] + (prefab_actor_sprites or []) + ui_image_sprites(p)
    done_anim: set[str] = set()
    for _, sprite in _all_sprites_flat:
        if sprite and sprite.asset and sprite.name not in done_anim:
            done_anim.add(sprite.name)
            L += anim_tables_for(p, sprite)
            L.append("")

    # ── Images d'interface ────────────────────────────────────────
    L += ui_images_lines(p, sprite_offsets, emit)

    # ── Visibilité des éléments d'interface ──────────────────────
    # APRÈS g_ui_regions/g_ui_images : les deux référencent un index de
    # CETTE table (`elem`), mais la lecture est par nom aux deux endroits
    # (`ui_element_index`), l'ordre d'émission n'a donc pas à être contraint
    # — placée ici pour rester avec le reste de l'UI.
    L += emit_ui_elements_c(p)
    L += emit_ui_lists_c(p, emit)

    # ── Sauvegarde ────────────────────────────────────────────────
    # Après globals.h (inclus plus haut) : les tables citent les index
    # GLOBAL_*, et le pilote appelle global_read/global_write.
    L += save_lines(p, emit)

    # ── Tile helpers (dispatch via pointeur) ──────────────────────
    L += gen_tile_helpers()
    if project_has_interactive(p):
        L += interact_helper_lines()
    if project_has_blockers(p):
        L += block_helper_lines()

    # ── Cartes de collision et palettes, par scène ────────────────
    L += scene_data_lines(p, all_scene_data)

    # ── Globals ───────────────────────────────────────────────────
    # Anneau + compteurs d'input : profondeur et bitset `buffered` calculés depuis les actions RÉELLEMENT
    # déclarées et interrogées par le projet (`compute_input_layout`, seule source, la même que
    # `lua_compiler.py` pour le catalogue de chaque script).
    _input_layout = compute_input_layout(p)
    L += globals_lines(p, all_scene_data, scene_pis, n_actors, n_oam_entries, _input_layout)

    # Spawn helpers — un jeu par scène (`spawn_<Scène>_<Prefab>`), chacun contre
    # SA plage OAM et SA banque de palette OBJ.
    for d, spi in zip(all_scene_data, scene_pis):
        _obj_layout = scene_bank_layout(p, d["scene"], "obj")
        L += section_spawn(spi, p, _obj_layout,
                            actor_defined_events=actor_defined_events)

    # Émis dès qu'UNE scène a de l'UI OBJ (le pointeur est projet-global, posé par scene_init).
    if _any_obj_ui:
        L += text_actor_accessor_lines()

    if has_soundbank:
        L += sound_box_lines(p, sound_assets)

    # Indices (GLOBAUX) des acteurs de chaque scène dont le script est du Lua.
    scene_lua_idx: list[set[int]] = [
        lua_actor_indices(p, d["scene_actors"], off) for off, d in zip(scene_offsets, all_scene_data)]

    # ── scene_init_X() par scène ──────────────────────────────────
    for i, d in enumerate(all_scene_data):
        sc         = d["scene"]
        act_off    = scene_offsets[i]
        bgi_d      = scene_bgi[i]
        sa         = d["scene_actors"]

        L += gen_scene_init(
            p, sc, act_off, bgi_d, sa, scene_lua_idx[i], scene_pis[i],
            sprite_offsets, scene_dispcnt(p, sc, bgi_d, bool(sprite_offsets)), has_sound, sound_assets,
            actor_defined_events=actor_defined_events,
            obj_text_oam=obj_text_band(p, sc, obj_text_tile, emit), obj_text_tile=obj_text_tile,
            emit=emit,
            affine_info=compute_affine_info(act_off, sa, _var_names(p)),
        )

    # ── scene_tick_X() par scène ──────────────────────────────────
    for i, d in enumerate(all_scene_data):
        sc      = d["scene"]
        act_off = scene_offsets[i]
        sa      = d["scene_actors"]

        L += gen_scene_tick(
            p, sc, act_off, scene_bgi[i], sa, scene_lua_idx[i], scene_pis[i],
            sprite_offsets, sprite_nframes, collision_pairs(p, sa, act_off, scene_lua_idx[i]),
            actor_defined_events=actor_defined_events,
            affine_info=compute_affine_info(act_off, sa, _var_names(p)),
            input_layout=_input_layout,
        )

    # ── Table des scènes, acteur par nom, fondu ───────────────────
    n_scenes = len(all_scene_data)
    trans = scene_transitions(p, all_scene_data)
    # Aucune scène n'a de transition → rien de tout ceci n'est émis : un projet
    # qui n'en veut pas garde la bascule sèche d'avant, au bit près.
    has_transitions = any(m for m, _, _ in trans)
    L += vtable_lines(all_scene_data, trans, has_transitions)
    L += actor_lookup_lines(p, all_scene_data)
    if has_transitions:
        L += scene_enter_lines(n_scenes)

    # ── Transitions musicales ────────────────────
    # Un seul point d'écriture du volume de module et de la bascule, comme la caméra n'a qu'un seul
    # point d'écriture de sa position : deux mécanismes qui écrivent le même registre sans se
    # coordonner, c'est le défaut qu'on a déjà corrigé une fois.
    if has_soundbank:
        L += music_runtime_lines(p, sound_assets)
        L += music_transition_tick_lines()
    elif has_sound:
        L += music_runtime_stub_lines()

    # ── main() ────────────────────────────────────────────────────
    L += main_lines(p, sprite_offsets, start_idx, start_scene, n_scenes, has_sound, soundbank_h, has_transitions)

    out = p.src_dir / "main.c"
    build_output.write(out, "\n".join(L) + "\n")
    if emit:
        emit("log_line", f"[gen] {out.relative_to(p.root)}")
    return True
